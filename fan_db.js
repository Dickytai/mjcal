// ========== 番數計算 function ==========
function getFanValue(fan) {
    if (typeof fan === 'number') return fan;
    if (typeof fan === 'string') {
        if (fan === 'x2') return 'x2';
        if (fan === 'n') return 'n';
        return parseInt(fan) || 0;
    }
    if (typeof fan === 'object') {
        // 明/暗 or 其他複合
        return fan;  // 返回object，等調用者处理
    }
    return 0;
}

function calculateTotalFans(fansList, options = {}) {
    let total = 0;
    const breakdown = [];
    const { isMing = false, isZimo = false, isLian = 0, isLa = 0, isZhuang = false } = options;
    
    for (const fanName of fansList) {
        const fan = FAN_DATABASE[fanName] || FAN_BY_NAME[fanName];
        if (!fan) continue;
        
        const value = getFanValue(fan);
        
        if (typeof value === 'number') {
            total += value;
            breakdown.push({ name: fanName, value });
        } else if (value === 'x2') {
            // 反雪: 總番數 x2
            total = total * 2;
            breakdown.push({ name: fanName, value: 'x2' });
        } else if (value === 'n') {
            // 連/拉: 2n番
            const n = fanName === '連' ? isLian : isLa;
            const add = 2 * n;
            total += add;
            breakdown.push({ name: fanName, value: add, n });
        } else if (typeof value === 'object' && value.Ming !== undefined) {
            // 明/暗 複合
            const add = isMing ? value.Ming : value.暗;
            total += add;
            breakdown.push({ name: fanName, value: add, type: isMing ? '明' : '暗' });
        }
    }
    
    return { total, breakdown };
}

