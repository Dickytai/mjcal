#!/bin/bash
# 麻將計算機 自動化測試
# 分為13張模式和16張模式

echo "🀄 麻將計算機 測試"
echo "============================================"

cd /home/tai/mjcal

run_test() {
    local name="$1"
    local tiles="$2"
    local mode="$3"
    
    echo ""
    echo "📋 $name (${mode}張)"
    result=$(node mj_calc.js waiting "$tiles" "0" "$mode" 2>&1)
    echo "   結果: $result"
}

echo ""
echo "========== 13張模式測試 =========="

# 標準13張聽牌
run_test "標準13張聽牌" '["1m","2m","3m","4m","5m","6m","7m","8m","9m","1s","1s","1s","1s"]' 13

# 七對子 (6對+1單張=13張=聽牌)
run_test "七對子聽牌" '["1m","1m","2m","2m","3m","3m","4m","4m","5m","5m","6m","6m","7m"]' 13

# 七對子 (7對=14張=胡牌)
run_test "七對子胡牌" '["1m","1m","2m","2m","3m","3m","4m","4m","5m","5m","6m","6m","7m","7m"]' 13

# 十三幺 (13孤張=差1張)
run_test "十三幺(13孤張)" '["1m","9m","1s","9s","1p","9p","1z","2z","3z","4z","5z","6z","7z"]' 13

# 十三幺 (13孤張+1張=14張=胡牌)
run_test "十三幺胡牌" '["1m","9m","1s","9s","1p","9p","1z","2z","3z","4z","5z","6z","7z","1m"]' 13

# 碰碰和 (4刻+1對)
run_test "碰碰和" '["1m","1m","1m","2m","2m","2m","3m","3m","3m","4m","4m","4m","5m"]' 13

echo ""
echo "========== 16張模式測試 =========="

# 標準16張聽牌
run_test "標準16張聽牌" '["1m","1m","1m","2m","2m","2m","3m","3m","3m","4m","5m","6m","7m","8m","9m","9m"]' 16

# 嚦咕嚦咕 - 7對+1坎=17張胡牌
run_test "嚦咕嚦咕胡牌" '["1m","1m","2m","2m","3m","3m","4m","4m","5m","5m","6m","6m","7m","7m","8m","8m","8m"]' 16

# 嚦咕嚦咕 - 8對=16張=聽8張
run_test "嚦咕嚦咕(8對)" '["1m","1m","2m","2m","3m","3m","4m","4m","5m","5m","6m","6m","7m","7m","8m","8m"]' 16

# 嚦咕嚦咕 - 6對+1坎+1孤張=16張=聽1張
run_test "嚦咕嚦咕(6對+1坎)" '["1m","1m","2m","2m","3m","3m","4m","4m","5m","5m","6m","6m","7m","7m","7m","9m"]' 16

# 嚦咕嚦咕 - 5對+2坎=16張=聽2張
run_test "嚦咕嚦咕(5對+2坎)" '["1m","1m","2m","2m","3m","3m","4m","4m","4m","5m","5m","5m","6m","6m","7m","7m"]' 16

# 十六不搭 (7字+9數牌)
run_test "十六不搭" '["1m","1m","9m","9m","1s","1s","9s","9s","1p","1p","9p","9p","1z","1z","2z","2z"]' 16

# 十六不搭聽牌
run_test "十六不搭(13張)" '["1m","1m","9m","1s","1s","9s","1p","1p","9p","1z","1z","2z","2z"]' 16

# 十三幺 (13孤張+1組面子=16張=聽牌)
run_test "十三幺(16張)" '["1m","9m","1s","9s","1p","9p","1z","2z","3z","4z","5z","6z","7z","4p","5p","6p"]' 16

# 對對糊 (5刻+1對)
run_test "對對糊" '["1m","1m","1m","2m","2m","2m","3m","3m","3m","4m","4m","4m","5m","5m","5m","6m"]' 16

# 清一色
run_test "清一色" '["1m","1m","1m","2m","2m","2m","3m","3m","3m","4m","5m","6m","7m","8m","9m","9m"]' 16

# 混一色
run_test "混一色" '["1m","1m","1m","2m","2m","2m","3m","3m","3m","4m","5m","6m","7m","8m","1z","1z"]' 16

# 大三元
run_test "大三元" '["5z","5z","5z","6z","6z","6z","7z","7z","7z","1m","1m","1m","2m","2m"]' 16

# 小三元
run_test "小三元" '["5z","5z","5z","6z","6z","7z","7z","7z","1m","1m","1m","2m","2m","2m"]' 16

echo ""
echo "========== 百搭牌測試 =========="

# 皇百搭 - 聽34款
run_test "皇百搭" '["1m","1m","1m","2m","2m","2m","3m","3m","3m","4m","4m","4m","5m","5m","5m","皇"]' 16

# 合百搭 - 聽27款
run_test "合百搭" '["1m","1m","1m","2m","2m","2m","3m","3m","3m","4m","4m","4m","5m","5m","5m","合"]' 16

echo ""
echo "============================================"
echo "✅ 測試完成!"
